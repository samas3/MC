def rm(n):
    r = ''
    ir = {'1000000': '§nM§r', '900000': '§nCM§r', '500000': '§nD§r', '400000': '§nCD§r', '100000': '§nC§r', '90000': '§nXC§r', '50000': '§nL§r', '40000': '§nXL§r', '10000': '§nX§r', '9000': '§nIX§r', '5000': '§nV§r', '4000': '§nIV§r', '1000': 'M', '900': 'CM', '500': 'D', '400': 'CD', '100': 'C', '90': 'XC', '50': 'L','40': 'XL', '10': 'X', '9': 'IX', '5': 'V', '4': 'IV', '1': 'I'}
    for k, v in ir.items():
        tmp = n // int(k)
        if tmp:
            r += tmp * v
            n -= tmp * int(k)
    return r
